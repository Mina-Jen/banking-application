import js from '@eslint/js'
import globals from 'globals'
import reactHooks from 'eslint-plugin-react-hooks'
import reactRefresh from 'eslint-plugin-react-refresh'
import tseslint from 'typescript-eslint'

/**
 * Lint gate for the frontend. Two toolchains already guard this code -- `tsc -b`
 * (npm run typecheck) and Vitest -- so ESLint is here for what they cannot see:
 * unreachable/unused code, React hook dependency bugs, and accidental globals.
 * Rules that only express a style preference are left off; the CI job must stay
 * a signal, not a wall of noise.
 */
export default tseslint.config(
  {
    ignores: [
      'dist/',
      'coverage/',
      'test-results/',
      'playwright-report/',
      // Generated by `npm run generate:api`; hand-linting a machine-written
      // OpenAPI type dump produces nothing actionable.
      'src/api/schema.d.ts',
    ],
  },

  {
    files: ['src/**/*.{ts,tsx}'],
    extends: [js.configs.recommended, ...tseslint.configs.recommended],
    plugins: {
      'react-hooks': reactHooks,
      'react-refresh': reactRefresh,
    },
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: 'module',
      globals: globals.browser,
    },
    rules: {
      ...reactHooks.configs.recommended.rules,
      'react-refresh/only-export-components': ['warn', { allowConstantExport: true }],
      // An unused parameter is usually a callback signature requirement
      // (e.g. (_, value) => ...), so the leading-underscore escape is allowed.
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
    },
  },

  {
    // Node-side files: the build/test configs and helper scripts, not shipped
    // to the browser.
    files: ['*.{ts,js,mjs}', 'scripts/**/*.mjs'],
    extends: [js.configs.recommended, ...tseslint.configs.recommended],
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: 'module',
      globals: globals.node,
    },
    rules: {
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
    },
  },
)
